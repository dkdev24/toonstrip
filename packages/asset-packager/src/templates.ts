/**
 * Text files the packager writes alongside the art: the pack's NOTICE and
 * README, and the `source.json` scaffold for `init`.
 */

import type { SourceJson } from "./source.js";
import { DEFAULT_SPEC, EMOTION_LIST } from "./spec.js";

export function noticeFile(json: SourceJson): string {
  const lines = [
    `${json.name} — toonstrip asset pack`,
    ``,
    `License: ${json.license}`,
  ];
  if (json.description) lines.push(``, json.description);
  if (json.attribution) lines.push(``, `Attribution:`, json.attribution);
  lines.push(
    ``,
    `Built with @toonstrip/asset-packager from a source pack of per-pose PNGs.`,
    `The art is the work of the pack author; the packager adds no content.`,
    ``,
  );
  return lines.join("\n");
}

export function readmeFile(json: SourceJson, characters: string[], backdrops: string[]): string {
  return `# ${json.name}

${json.description ?? `A toonstrip asset pack.`}

- **Characters:** ${characters.length ? characters.map((c) => `\`${c}\``).join(", ") : "none"}
- **Backdrops:** ${backdrops.length ? backdrops.map((b) => `\`${b}\``).join(", ") : "none"}
- **License:** ${json.license}

Use the ids above as \`character\` and \`backdrop\` values in a
\`ComicStripDocument\`. To render with the CLI:

\`\`\`sh
toonstrip render strip.json --out strip.png --pack ./${json.name}
\`\`\`

Generated by \`@toonstrip/asset-packager\`. Rebuild it from the source PNGs
rather than editing \`pack.json\` or the per-character manifests by hand:

\`\`\`sh
toonstrip-pack build <source-dir> --out <this-dir>
\`\`\`
`;
}

export function sourceJsonScaffold(name: string): string {
  return `${JSON.stringify(
    {
      name,
      version: "0.1.0",
      license: "MIT",
      description: `A toonstrip asset pack.`,
      attribution: "Art by <your name>.",
      spec: { cell: DEFAULT_SPEC.cell, backdropSize: DEFAULT_SPEC.backdropSize, joinOverlap: DEFAULT_SPEC.joinOverlap },
      characters: [
        {
          id: "example",
          name: "Example",
          type: "COMPLEX",
          torsoFirst: false,
        },
      ],
      backdrops: [{ id: "example-room" }],
    },
    null,
    2,
  )}\n`;
}

export function promptChecklist(): string {
  return `# Pose checklist

One transparent, square PNG per file. Filenames must be exactly:

    <kind>-<EMOTION>[@<intensity>][-<variant>].png

\`kind\` is \`face\` or \`torso\`. \`EMOTION\` is one of:

${EMOTION_LIST.map((e) => `- ${e}`).join("\n")}

Required: \`face-NEUTRAL.png\`, \`torso-NEUTRAL.png\`.
Recommended next: the eight wheel faces (HAPPY, COY, BORED, SCARED, SAD,
ANGRY, SHOUT, LAUGH) and the gesture torsos (WAVE, POINTOTHER, POINTSELF,
DOUBLEPOINT, SHRUG).

See \`docs/asset-image-spec.md\` for the drawing rules, then run:

    toonstrip-pack validate <source-dir>
    toonstrip-pack build <source-dir> --out <out-dir> --preview joins.png

## Generating with an image model?

Prefer one **sheet** — a single image holding a grid of these cells — over one
generation per pose: identity cannot drift between cells, and each pose is
registered against the NEUTRAL cell. The grid can be any shape you declare.

    toonstrip-pack template --out ref.png
    toonstrip-pack template --out scenes.png --kind backdrop --ids hall,cellar --columns 2

Each run prints the \`source.json\` fragment for the sheet and a prompt skeleton.
See \`docs/asset-sheets.md\`.
`;
}
