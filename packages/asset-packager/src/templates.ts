/**
 * Text files the packager writes alongside the art: the pack's NOTICE and
 * README, the `source.json` scaffold for `init`, and — with `--npm` — the
 * loader skeleton that makes the output directory an installable package,
 * mirroring `@toonstrip/pack-example` (every pack carries its own copy of the
 * pack types rather than importing a shared one; see `docs/packs.md`).
 */

import type { SourceJson } from "./source.js";
import { DEFAULT_SPEC, EMOTION_LIST } from "./spec.js";

export function noticeFile(json: SourceJson): string {
  const lines = [
    `${json.name} — toonstrip asset pack`,
    ``,
    `License: ${json.license}`,
  ];
  if (json.description) lines.push(``, json.description);
  if (json.attribution) lines.push(``, `Attribution:`, json.attribution);
  lines.push(
    ``,
    `Built with @toonstrip/asset-packager from a source pack of per-pose PNGs.`,
    `The art is the work of the pack author; the packager adds no content.`,
    ``,
  );
  return lines.join("\n");
}

export function readmeFile(json: SourceJson, characters: string[], backdrops: string[]): string {
  return `# ${json.name}

${json.description ?? `A toonstrip asset pack.`}

- **Characters:** ${characters.length ? characters.map((c) => `\`${c}\``).join(", ") : "none"}
- **Backdrops:** ${backdrops.length ? backdrops.map((b) => `\`${b}\``).join(", ") : "none"}
- **License:** ${json.license}

Use the ids above as \`character\` and \`backdrop\` values in a
\`ComicStripDocument\`. To render with the CLI:

\`\`\`sh
toonstrip render strip.json --out strip.png --pack ./${json.name}
\`\`\`

Generated by \`@toonstrip/asset-packager\`. Rebuild it from the source PNGs
rather than editing \`pack.json\` or the per-character manifests by hand:

\`\`\`sh
toonstrip-pack build <source-dir> --out <this-dir>
\`\`\`
`;
}

