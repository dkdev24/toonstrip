// Embeds schema.json as a TS object literal so the validator has no runtime
// file to load (works identically under plain Node, bundlers, and browsers —
// no JSON-import-assertion or fs dependency). `npm run build`'s prebuild hook
// calls this before `tsc` runs; `src/schema-data.ts` is gitignored, tsc
// compiles it like any other source file.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaJson = readFileSync(join(pkgRoot, "src/schema.json"), "utf-8").trim();

writeFileSync(
  join(pkgRoot, "src/schema-data.ts"),
  `// Generated by scripts/embed-schema.mjs from schema.json — do not edit.\nexport default ${schemaJson} as const;\n`,
);
